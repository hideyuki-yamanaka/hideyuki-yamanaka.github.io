/** パネルの本文（複数行文字列）を段落→行の二次元配列に変換。
    空行で段落を区切り、段落内は改行で行に分ける（空行・空白は捨てる） */
export function parseMsgBody(body: string): string[][] {
  return (body || "")
    .replace(/\r\n/g, "\n")
    .split(/\n[ \t]*\n+/) /* 空行（空白のみ含む）で段落分割 */
    .map((block) =>
      block
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => l.length > 0)
    )
    .filter((block) => block.length > 0);
}

